const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const parentId = process.argv[2];
const mdPath = process.argv[3] || 'walkthrough.md';

if (!parentId) {
  console.error('❌ Error: PARENT_ID is required! Usage: node post-walkthrough.js <parent_prd_issue_id> [walkthrough.md]');
  process.exit(1);
}

if (!fs.existsSync(mdPath)) {
  console.error(`❌ Error: Walkthrough file not found at ${mdPath}`);
  process.exit(1);
}

const content = fs.readFileSync(mdPath, 'utf8');
const commentBody = `> *This was generated by AI during triage.*\n\n${content}`;
const tempFilePath = path.join(process.cwd(), `.temp-comment-${Date.now()}.md`);

try {
  fs.writeFileSync(tempFilePath, commentBody, 'utf8');
  
  console.log(`Posting walkthrough comment to GitHub issue #${parentId}...`);
  execSync(`gh issue comment ${parentId} --body-file="${tempFilePath}"`, { stdio: 'inherit' });
  
  console.log(`Closing GitHub issue #${parentId}...`);
  execSync(`gh issue close ${parentId}`, { stdio: 'inherit' });
  
  console.log(`🎉 Successfully posted walkthrough and closed issue #${parentId}!`);
} catch (error) {
  console.error('❌ Error executing post-walkthrough:', error.message);
  process.exit(1);
} finally {
  if (fs.existsSync(tempFilePath)) {
    fs.unlinkSync(tempFilePath);
  }
}
