const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const USAGE = 'Usage: node post-walkthrough.js <parent_prd_issue_number> [walkthrough.md] [--close]';

const args = process.argv.slice(2);
const close = args.includes('--close');
const positional = args.filter(arg => arg !== '--close');
const parentId = (positional[0] || '').replace(/^#/, '');
const mdPath = positional[1] || 'walkthrough.md';

if (!/^\d+$/.test(parentId)) {
  console.error(`❌ Error: a numeric parent PRD issue number is required.\n${USAGE}`);
  process.exit(2);
}

if (!fs.existsSync(mdPath)) {
  console.error(`❌ Error: Walkthrough file not found at ${mdPath}`);
  process.exit(1);
}

const content = fs.readFileSync(mdPath, 'utf8');
const commentBody = `> *This was generated by AI during triage.*\n\n${content}`;
// Outside the repo, so the temp file never shows up in git status.
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'prd-walkthrough-'));
const tempFilePath = path.join(tempDir, 'comment.md');

try {
  fs.writeFileSync(tempFilePath, commentBody, 'utf8');

  console.log(`Posting walkthrough comment to GitHub issue #${parentId}...`);
  execFileSync('gh', ['issue', 'comment', parentId, '--body-file', tempFilePath], { stdio: 'inherit' });

  if (close) {
    console.log(`Closing GitHub issue #${parentId}...`);
    execFileSync('gh', ['issue', 'close', parentId], { stdio: 'inherit' });
    console.log(`🎉 Posted the walkthrough and closed issue #${parentId}.`);
  } else {
    console.log(`✅ Posted the walkthrough to issue #${parentId}. Left it open; close it with: gh issue close ${parentId}`);
  }
} catch (error) {
  console.error('❌ Error executing post-walkthrough:', error.message);
  process.exit(1);
} finally {
  fs.rmSync(tempDir, { recursive: true, force: true });
}
